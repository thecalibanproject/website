// Writes src/content/docs/reference/api.md from core's OpenAPI contract.
//
//   node scripts/gen-api-reference.mjs [path/to/openapi.yaml]
//
// Default input: ../../core/api/openapi.yaml (the core checkout next to the website repo).
// The output is committed, so building the docs never needs core. Regenerate after an API change.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const here = fileURLToPath(new URL('..', import.meta.url));
const input = resolve(process.argv[2] ?? resolve(here, '../../core/api/openapi.yaml'));
const out = resolve(here, 'src/content/docs/reference/api.md');
const spec = parse(readFileSync(input, 'utf8'));

// Plain names for the API's tags, in reading order. The API name stays in code.
const TAGS = [
  ['inference', 'Gateway: send requests', 'The data plane (port 8080). Apps call it with a workspace API key (`cal_...`).'],
  ['tenants', 'Workspaces', 'Workspaces are `tenants` in the API: keys, privacy, limits, runs and approvals.'],
  ['provider-keys', 'Provider accounts', 'Your own keys for outside model providers (BYOK), sealed and never returned.'],
  ['models', 'Models and model servers', 'The model catalogue and the shared model servers (`providers`).'],
  ['datasources', 'Data connections', 'Read-only database connections (`datasources`) and their scans (`introspect`).'],
  ['ontology', 'Data dictionary', 'The reviewed business names for your data (`ontology`).'],
  ['nodes', 'Assistants, versions and runs', 'Assistants are `nodes` in the API.'],
  ['evals', 'Tests and going live', 'Test cases (`golden-set`), test runs (`evals`), the go-live rules (`eval-policy`) and the check (`gate`).'],
  ['tools', 'Connected systems', 'Tool servers (MCP) and the actions a person approved.'],
  ['rag', 'Knowledge', 'Document libraries (`rag/collections`) and their documents.'],
  ['usage', 'Usage and audit', 'Usage events, totals and the audit log.'],
  ['system', 'System', 'Health, keys, users, roles and the split-mode endpoints.'],
  ['auth', 'Sign-in', 'Single sign-on for the console (`/auth/*`).'],
];

const METHODS = ['get', 'post', 'put', 'patch', 'delete'];
const dashFree = (s) => String(s ?? '').replace(/\s*[\u2013\u2014]\s*/g, ': ');
const refName = (ref) => ref?.split('/').pop();
const deref = (o) => {
  let cur = o;
  for (let i = 0; cur?.$ref && i < 10; i++) {
    const path = cur.$ref.replace(/^#\//, '').split('/');
    cur = path.reduce((a, k) => a?.[k], spec);
  }
  return cur ?? {};
};
const cell = (s) => dashFree(s).replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ').trim();
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

function typeOf(schema) {
  if (!schema) return '';
  if (schema.$ref) return `[${refName(schema.$ref)}](#${slug(refName(schema.$ref))})`;
  if (schema.type === 'array') return `array of ${typeOf(schema.items)}`;
  if (schema.enum) return schema.enum.map((v) => `\`${v}\``).join(', ');
  if (schema.oneOf || schema.anyOf) return (schema.oneOf ?? schema.anyOf).map(typeOf).join(' or ');
  if (Array.isArray(schema.type)) return schema.type.join(' or ');
  return schema.type ?? 'object';
}

function bodySchema(content) {
  const c = content?.['application/json'] ?? Object.values(content ?? {})[0];
  return c?.schema;
}

// Collect operations by tag.
const byTag = new Map(TAGS.map(([t]) => [t, []]));
for (const [path, item] of Object.entries(spec.paths)) {
  for (const m of METHODS) {
    const op = item[m];
    if (!op) continue;
    const tag = op.tags?.[0] ?? 'system';
    if (!byTag.has(tag)) byTag.set(tag, []);
    byTag.get(tag).push({ path, method: m.toUpperCase(), op, params: [...(item.parameters ?? []), ...(op.parameters ?? [])] });
  }
}

const L = [];
L.push('---');
L.push('title: HTTP API');
L.push('description: Every endpoint of the gateway (data plane) and the admin API (control plane), generated from the OpenAPI contract.');
L.push('---');
L.push('');
L.push(`<!-- Generated by scripts/gen-api-reference.mjs from core api/openapi.yaml (OpenAPI ${spec.openapi}, API version ${spec.info.version}). Do not edit by hand: change the contract in core and run npm run gen:api. -->`);
L.push('');
L.push('Caliban has two HTTP surfaces. This page lists every endpoint of both, grouped by what you do with them.');
L.push('');
L.push('| Surface | Default address | Who calls it | Authentication |');
L.push('|---|---|---|---|');
L.push('| Gateway (data plane) | `http://<host>:8080` | Your apps, with OpenAI or Anthropic SDKs or the Caliban SDKs | A workspace API key: `Authorization: Bearer cal_...` |');
L.push('| Admin API (control plane) | `http://<host>:8081` | The console, the SDK admin clients, scripts | A console session, an access token from your identity provider, or the admin token |');
L.push('');
L.push('Plain names on this page, API names in code: a workspace is a `tenant`, an assistant is a `node`, a run is one conversation with an assistant, a topic is an `intent`, the data dictionary is the `ontology`, a data connection is a `datasource`, a document library is a `rag` collection. See the [glossary](glossary.md).');
L.push('');
L.push('Every admin route checks one permission: `401` means you are not signed in, `403` means your roles do not allow it. A successful `DELETE` returns `204` and writes one audit row; a repeat delete is `404`. Errors use one envelope, described in [Errors](errors.md). Response headers of the gateway are in [Response headers](response-headers.md).');
L.push('');
L.push('The machine-readable contract is `api/openapi.yaml` in the core repository.');
L.push('');

for (const [tag, title, intro] of TAGS) {
  const ops = byTag.get(tag) ?? [];
  if (!ops.length) continue;
  L.push(`## ${title}`);
  L.push('');
  L.push(intro);
  L.push('');
  L.push('| Method | Path | What it does |');
  L.push('|---|---|---|');
  for (const { path, method, op } of ops) L.push(`| \`${method}\` | \`${path}\` | ${cell(op.summary)} |`);
  L.push('');
  for (const { path, method, op, params } of ops) {
    L.push(`### ${cell(op.summary ?? `${method} ${path}`)}`);
    L.push('');
    L.push('```http');
    L.push(`${method} ${path}`);
    L.push('```');
    L.push('');
    if (op.description) {
      L.push(dashFree(op.description).trim());
      L.push('');
    }
    const ps = params.map(deref).filter((p) => p.name);
    if (ps.length) {
      L.push('| Parameter | In | Type | Required | Meaning |');
      L.push('|---|---|---|---|---|');
      for (const p of ps)
        L.push(`| \`${p.name}\` | ${p.in} | ${cell(typeOf(p.schema))}${p.schema?.default !== undefined ? ` (default \`${p.schema.default}\`)` : ''} | ${p.required ? 'yes' : 'no'} | ${cell(p.description)} |`);
      L.push('');
    }
    const body = bodySchema(deref(op.requestBody).content);
    if (body) {
      L.push(`**Request body:** ${typeOf(body)}${op.requestBody?.required ? '' : ' (optional)'}`);
      L.push('');
    }
    const rs = Object.entries(op.responses ?? {});
    if (rs.length) {
      L.push('| Status | Meaning | Body |');
      L.push('|---|---|---|');
      for (const [code, r0] of rs) {
        const r = deref(r0);
        L.push(`| \`${code}\` | ${cell(r.description)} | ${cell(typeOf(bodySchema(r.content)))} |`);
      }
      L.push('');
    }
  }
}

// Schemas
const schemas = spec.components?.schemas ?? {};
L.push('## Schemas');
L.push('');
L.push('The request and response bodies named above, field by field. Links in the tables lead here.');
L.push('');
for (const [name, s0] of Object.entries(schemas)) {
  const s = deref(s0);
  L.push(`### ${name}`);
  L.push('');
  if (s.description) {
    L.push(dashFree(s.description).trim());
    L.push('');
  }
  const props = Object.entries(s.properties ?? {});
  const req = new Set(s.required ?? []);
  if (props.length) {
    L.push('| Field | Type | Required | Meaning |');
    L.push('|---|---|---|---|');
    for (const [k, v] of props) L.push(`| \`${k}\` | ${cell(typeOf(v))} | ${req.has(k) ? 'yes' : 'no'} | ${cell(v.description)} |`);
    L.push('');
  } else if (s.enum) {
    L.push(`One of ${s.enum.map((v) => `\`${v}\``).join(', ')}.`);
    L.push('');
  } else if (s.oneOf || s.anyOf || s.allOf) {
    L.push(`Composed of ${(s.oneOf ?? s.anyOf ?? s.allOf).map(typeOf).join(', ')}.`);
    L.push('');
  }
}

writeFileSync(out, L.join('\n'));
console.log(`Wrote ${out} from ${input}: ${[...byTag.values()].flat().length} operations, ${Object.keys(schemas).length} schemas.`);
